'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const { fingerprint, similarity, analyze } = require('../detector.cjs');
const { configFromEnv, eligible, listFilters } = require('../config.cjs');
const { GENERATED_CODE, HUMAN_CODE, PEER_CODE, CONTEST } = require('../demo.cjs');

const at = '2026-10-31T08:00:00.000Z';
function current(code = GENERATED_CODE) { return { rid: '6ae59ff00000000000000001', domainId: 'system', uid: 42, pid: 2104,
    contest: CONTEST, submittedAt: at, fingerprint: fingerprint(code, 'cpp') }; }
function source(input = {}) { return { _id: 'job:1', jobId: '1', domainId: 'system', uid: 42, pid: 2104, mode: 'solve',
    completedAt: '2026-10-31T07:59:00.000Z', fingerprint: fingerprint(GENERATED_CODE, 'cpp'), ...input }; }

test('lexical hashes erase formatting/comments, preserve string and numeric semantics, and tolerate identifier renames', () => {
    const fp = fingerprint(GENERATED_CODE, 'cpp');
    const reformatted = fingerprint(GENERATED_CODE.replace(/    /g, '\t').replace('// Count subarrays whose sum is exactly target.', '// different prose'), 'cc.cc17o2');
    assert.equal(fp.exactHash, reformatted.exactHash);
    const renamed = fingerprint(GENERATED_CODE.replace(/prefixFrequency/g, 'freq').replace(/prefixSum/g, 'acc'), 'cpp');
    assert.notEqual(fp.exactHash, renamed.exactHash); assert.equal(similarity(fp, renamed), 1);
    assert.notEqual(fingerprint('int main(){return 1;}', 'cpp').exactHash, fingerprint('int main(){return 2;}', 'cpp').exactHash);
    assert.notEqual(fingerprint('puts("one");', 'cpp').exactHash, fingerprint('puts("two");', 'cpp').exactHash);
    assert.equal(fingerprint('s = "# not a comment"\n# real comment\nprint(s)', 'python3').tokenCount, 7);
    assert.equal(fingerprint('s = "# not a comment"\n# other comment\nprint(s)', 'python3').exactHash,
        fingerprint('s = "# not a comment"\nprint(s)', 'python3').exactHash);
});

test('only a same-user, same-domain, same-problem prior complete AI solution has traceable priority', () => {
    const result = analyze({ current: current(), sources: [source()] });
    assert.equal(result.priority, 'high'); assert.equal(result.score, 90); assert.equal(result.conclusion, 'undetermined');
    assert.equal(result.signals[0].kind, 'assistant_match'); assert.equal(result.signals[0].metrics.exact, true);
    const cases = [{ uid: 41 }, { domainId: 'other' }, { pid: 2105 }, { mode: 'debug' }, { completedAt: '2026-10-31T08:00:01Z' },
        { completedAt: '2026-10-29T08:00:00Z' }, { completedAt: 'invalid' }];
    for (const input of cases) assert.equal(analyze({ current: current(), sources: [source(input)] }).signals.length, 0, JSON.stringify(input));
});

test('cross-contest/domain similarity is excluded and copying cannot produce high AI priority', () => {
    const submission = current(PEER_CODE);
    const peer = { ...submission, rid: '6ae59fee0000000000000001', uid: 43, submittedAt: '2026-10-31T07:50:00Z' };
    const result = analyze({ current: submission, peers: [peer] });
    assert.equal(result.priority, 'medium'); assert.equal(result.score, 45);
    assert.equal(result.signals[0].kind, 'peer_similarity'); assert.equal(result.conclusion, 'undetermined');
    for (const input of [{ contest: null }, { contest: '6a0000000000000000000099' }, { domainId: 'other' }, { uid: 42 }, { pid: 999 }, { submittedAt: '2026-10-31T09:00:00Z' }]) {
        assert.equal(analyze({ current: submission, peers: [{ ...peer, ...input }] }).signals.length, 0);
    }
});

test('short answers, unsupported languages, missing/file sources and oversized code remain undetermined', () => {
    for (const fp of [fingerprint('int main(){return 0;}', 'cpp'), fingerprint(null, 'cpp'), fingerprint('print(1)', 'brainfuck'), fingerprint('a'.repeat(65537), 'cpp')]) {
        const result = analyze({ current: { ...current(), fingerprint: fp }, sources: [source()] });
        assert.equal(result.priority, 'insufficient'); assert.equal(result.score, 0); assert.equal(result.signals.length, 0); assert.equal(result.conclusion, 'undetermined');
    }
});

test('AI declarations and style changes remain weak signals; mere detailed comments do not imply AI', () => {
    const marked = analyze({ current: current(HUMAN_CODE + '\n// Generated by ChatGPT\n') });
    assert.equal(marked.signals[0].kind, 'ai_marker'); assert.equal(marked.priority, 'low');
    const unmarked = analyze({ current: current(GENERATED_CODE) }); assert.equal(unmarked.signals.length, 0);
    const now = current();
    now.fingerprint.style = { commentRatio: .35, identifierLength: 12, underscoreRatio: .8, camelRatio: .8, tabRatio: 1 };
    const history = Array.from({ length: 5 }, (_, i) => ({ ...now, uid: 42, pid: 100 + i, submittedAt: '2026-10-30T08:00:00Z',
        fingerprint: { ...now.fingerprint, style: { commentRatio: 0, identifierLength: 1, underscoreRatio: 0, camelRatio: 0, tabRatio: 0 } } }));
    const result = analyze({ current: now, history });
    assert.equal(result.signals[0].kind, 'style_change'); assert.equal(result.priority, 'low');
    assert.equal(analyze({ current: now, history: history.slice(0, 4) }).signals.length, 0);
});

test('default scope is contest-only; pretests, hacks, other domains and invalid configuration are rejected', () => {
    const cfg = configFromEnv({}); const record = { _id: current().rid, domainId: 'system', uid: 42, pid: 2104, contest: CONTEST };
    assert.equal(cfg.scope, 'contests'); assert.equal(eligible(record, cfg), true);
    for (const input of [{ contest: null }, { contest: '000000000000000000000000' }, { contest: '000000000000000000000001' }, { hackTarget: '1' }, { input: [] }, { domainId: 'other' }, { uid: 0 }]) {
        assert.equal(eligible({ ...record, ...input }, cfg), false);
    }
    for (const input of [{ DFACM_AI_WATCH_SCOPE: 'anything' }, { DFACM_AI_WATCH_DOMAINS: '*' }, { DFACM_AI_WATCH_RETENTION_DAYS: '999' }, { DFACM_AI_WATCH_CONTESTS: 'bad' }]) {
        assert.throws(() => configFromEnv(input));
    }
    assert.equal(listFilters({ uid: '42', days: '3' }).uid, 42);
    for (const input of [{ uid: '-1' }, { priority: 'ai' }, { cursor: 'wrong' }, { days: '8' }, { contest: { $ne: null } }]) assert.throws(() => listFilters(input));
});

test('E3 same-second source remains context, without a fabricated earlier claim or high priority', () => {
    for (const millis of [0, 100, 999]) {
        const result = analyze({ current: current(), sources: [source({ completedAt: new Date(Date.parse(at) + millis) })] });
        assert.equal(result.coverage.sourceCount, 1, `source at .${millis} must remain visible`);
        const signal = result.signals.find(v => v.kind === 'assistant_match');
        assert.ok(signal); assert.equal(signal.strength, 'context'); assert.equal(signal.weight, 0);
        assert.equal(signal.reference.timing, 'uncertain'); assert.equal(result.priority, 'low');
        assert.equal(result.score, 0); assert.equal(result.conclusion, 'undetermined');
        assert.doesNotMatch(signal.title + signal.detail, /先前|提交前/);
    }
    const earlier = analyze({ current: current(), sources: [source({ completedAt: new Date(Date.parse(at) - 1) })] });
    assert.equal(earlier.signals[0].reference.timing, 'earlier'); assert.equal(earlier.priority, 'high');
    assert.equal(analyze({ current: current(), sources: [source({ completedAt: new Date(Date.parse(at) + 1000) })] }).coverage.sourceCount, 0);
});

test('E3 uncertain perfect match cannot hide a temporally certain source or open the high gate', () => {
    const earlier = source({ _id: 'earlier', fingerprint: fingerprint(GENERATED_CODE.replace(/prefixSum/g, 'runningSum'), 'cpp') });
    const uncertain = source({ _id: 'same-second', completedAt: new Date(Date.parse(at) + 100) });
    const both = analyze({ current: current(), sources: [uncertain, earlier] });
    assert.equal(both.priority, 'high'); assert.equal(both.signals[0].reference.sourceId, 'earlier');
    const marked = current(GENERATED_CODE + '\n// Generated by ChatGPT');
    const result = analyze({ current: marked, sources: [uncertain], peers: [{ ...marked, uid: 43, rid: 'other', submittedAt: '2026-10-31T07:59:00Z' }] });
    assert.notEqual(result.priority, 'high'); assert.ok(result.score <= 65); assert.equal(result.conclusion, 'undetermined');
});
